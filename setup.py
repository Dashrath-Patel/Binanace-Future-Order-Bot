#!/usr/bin/env python3
"""
Setup Script - Interactive setup for Binance Futures Trading Bot
Helps users configure API keys and test the bot safely
"""

import os
import sys
import getpass
from pathlib import Path

def create_env_file():
    """Create .env file with user's API credentials"""
    print("🔧 Setting up Binance API Configuration")
    print("-" * 40)
    
    print("📝 You can get your API keys from:")
    print("   Testnet (Recommended): https://testnet.binancefuture.com/")
    print("   Production: https://www.binance.com/en/my/settings/api-management")
    print()
    
    # Get API credentials
    api_key = input("Enter your Binance API Key: ").strip()
    if not api_key:
        print("❌ API Key is required!")
        return False
    
    api_secret = getpass.getpass("Enter your Binance API Secret: ").strip()
    if not api_secret:
        print("❌ API Secret is required!")
        return False
    
    # Ask about testnet
    use_testnet = input("Use testnet for safe testing? (Y/n): ").strip().lower()
    testnet = use_testnet != 'n'
    
    # Create .env file
    env_content = f"""# Binance API Configuration
# Generated by setup script

BINANCE_API_KEY={api_key}
BINANCE_API_SECRET={api_secret}
BINANCE_TESTNET={'true' if testnet else 'false'}

# Note: Keep this file secure and never commit it to version control!
"""
    
    env_file = Path('.env')
    env_file.write_text(env_content)
    
    print(f"✅ Configuration saved to {env_file}")
    print(f"   Using {'testnet' if testnet else 'production'} environment")
    
    return True

def test_configuration():
    """Test the bot configuration"""
    print("\n🧪 Testing Bot Configuration")
    print("-" * 40)
    
    try:
        # Load environment variables
        from dotenv import load_dotenv
        load_dotenv()
        
        # Test configuration
        os.system("python test_bot.py")
        
        return True
        
    except Exception as e:
        print(f"❌ Configuration test failed: {e}")
        return False

def run_test_order():
    """Run a test order if user wants to"""
    print("\n🚀 Test Order")
    print("-" * 40)
    
    test_order = input("Run a small test order? (y/N): ").strip().lower()
    if test_order != 'y':
        return
    
    print("Running test market order...")
    print("Command: python src/market_orders.py BTCUSDT BUY 0.001 --testnet")
    
    confirm = input("Continue with test order? (y/N): ").strip().lower()
    if confirm == 'y':
        os.system("python src/market_orders.py BTCUSDT BUY 0.001 --testnet")
    else:
        print("Test order cancelled")

def show_usage_examples():
    """Show usage examples"""
    print("\n📖 Usage Examples")
    print("-" * 40)
    
    examples = [
        ("Market Order", "python src/market_orders.py BTCUSDT BUY 0.01"),
        ("Limit Order", "python src/limit_orders.py BTCUSDT BUY 0.01 65000.0"),
        ("OCO Order", "python src/advanced/oco.py BTCUSDT SELL 0.01 64000.0 66000.0"),
        ("TWAP Strategy", "python src/advanced/twap.py BTCUSDT BUY 1.0 60 --chunks 10"),
        ("Grid Strategy", "python src/advanced/grid_strategy.py BTCUSDT 0.01 64000.0 66000.0 --levels 10"),
        ("Unified Interface", "python bot.py market BTCUSDT BUY 0.01"),
    ]
    
    for name, command in examples:
        print(f"{name:15}: {command}")
    
    print(f"\n💡 Tips:")
    print(f"  - Always test on testnet first (add --testnet)")
    print(f"  - Start with small quantities")
    print(f"  - Check bot.log for detailed logs")
    print(f"  - Use 'python bot.py STRATEGY --help' for detailed help")

def main():
    """Main setup function"""
    print("🚀 Binance Futures Trading Bot Setup")
    print("=" * 40)
    
    # Check if .env already exists
    if Path('.env').exists():
        overwrite = input("Configuration file .env already exists. Overwrite? (y/N): ").strip().lower()
        if overwrite != 'y':
            print("Using existing configuration...")
        else:
            if not create_env_file():
                return 1
    else:
        if not create_env_file():
            return 1
    
    # Test configuration
    if not test_configuration():
        return 1
    
    # Offer test order
    run_test_order()
    
    # Show usage examples
    show_usage_examples()
    
    print("\n🎉 Setup completed successfully!")
    print("Your Binance Futures Trading Bot is ready to use.")
    
    return 0

if __name__ == "__main__":
    try:
        exit_code = main()
        sys.exit(exit_code)
    except KeyboardInterrupt:
        print("\n⚠️  Setup cancelled by user")
        sys.exit(1)
    except Exception as e:
        print(f"\n❌ Setup failed: {e}")
        sys.exit(1)
